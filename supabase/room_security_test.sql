-- Run against a disposable database with the migration applied. Rolls everything back.
begin;
insert into auth.users(id) values ('11111111-1111-1111-1111-111111111111'),('22222222-2222-2222-2222-222222222222'),('33333333-3333-3333-3333-333333333333');
do $$
declare r jsonb; joined jsonb; id text; code text; prefs jsonb; denied boolean;
begin
  perform set_config('request.jwt.claim.sub','11111111-1111-1111-1111-111111111111',true);
  r:=public.saantayo_room('create','{"name":"Test lunch","nickname":"Host","candidates":[{"id":"test","name":"Test venue","lat":14,"lng":120,"distance":1,"price":100,"vegetarian":null,"halal":null,"cuisines":["filipino"],"source":"demo"}]}');
  id:=r->>'id';code:=r->>'code';prefs:=r->'participants'->0->'prefs';
  assert not saantayo_private.valid_candidates(jsonb_set(r->'candidates','{0,price}','-1')),'Negative price accepted';
  assert not saantayo_private.valid_candidates(jsonb_set(r->'candidates','{0,price}','{}')),'Object price accepted';
  assert not saantayo_private.valid_candidates(jsonb_set(r->'candidates','{0,cuisines}','[{}]')),'Object cuisine accepted';
  assert (prefs->>'allowUnknown')::boolean=false,'Unknowns must be opt-in';
  perform set_config('request.jwt.claim.sub','33333333-3333-3333-3333-333333333333',true);
  denied:=false;begin perform public.saantayo_room('read',jsonb_build_object('id',id));exception when others then denied:=true;end;
  assert denied,'Nonmember read allowed';
  perform set_config('request.jwt.claim.sub','22222222-2222-2222-2222-222222222222',true);
  joined:=public.saantayo_room('join',jsonb_build_object('code',code,'nickname','Guest'));
  denied:=false;begin perform public.saantayo_room('start',jsonb_build_object('id',id,'candidates',r->'candidates'));exception when others then denied:=true;end;
  assert denied,'Guest start allowed';
  denied:=false;begin perform public.saantayo_room('finish',jsonb_build_object('id',id));exception when others then denied:=true;end;
  assert denied,'Guest finish allowed';
  perform set_config('request.jwt.claim.sub','11111111-1111-1111-1111-111111111111',true);
  perform public.saantayo_room('start',jsonb_build_object('id',id,'candidates',r->'candidates'));
  denied:=false;begin perform public.saantayo_room('finish',jsonb_build_object('id',id));exception when others then denied:=true;end;
  assert denied,'Incomplete ballots finalized';
  perform public.saantayo_room('vote',jsonb_build_object('id',id,'restaurant','test','value',2));
  r:=public.saantayo_room('read',jsonb_build_object('id',id));
  assert r->'participants'->0->'votes'->>'test'='2','Own vote missing';
  perform set_config('request.jwt.claim.sub','22222222-2222-2222-2222-222222222222',true);
  joined:=public.saantayo_room('read',jsonb_build_object('id',id));
  assert joined->'participants'->0->'votes'='{}'::jsonb,'Another participant ballot leaked';
  assert (joined->'participants'->0->>'voteCount')::integer=1,'Progress missing';
  perform public.saantayo_room('vote',jsonb_build_object('id',id,'restaurant','test','value',1));
  perform public.saantayo_room('undo',jsonb_build_object('id',id,'restaurant','test'));
  perform public.saantayo_room('vote',jsonb_build_object('id',id,'restaurant','test','value',2));
  perform set_config('request.jwt.claim.sub','11111111-1111-1111-1111-111111111111',true);
  r:=public.saantayo_room('finish',jsonb_build_object('id',id));
  assert r->>'status'='finished' and r->>'winnerId'='test','Incorrect result';
  assert saantayo_private.candidate_score(r->'candidates'->0,r->'participants')=92.9,'Domain score mismatch';
  denied:=false;begin perform public.saantayo_room('vote',jsonb_build_object('id',id,'restaurant','test','value',0));exception when others then denied:=true;end;
  assert denied,'Finished vote was editable';
  perform public.saantayo_room('restart',jsonb_build_object('id',id));
  perform public.saantayo_room('remove',jsonb_build_object('id',id,'user','22222222-2222-2222-2222-222222222222'));
  perform set_config('request.jwt.claim.sub','22222222-2222-2222-2222-222222222222',true);
  denied:=false;begin perform public.saantayo_room('read',jsonb_build_object('id',id));exception when others then denied:=true;end;
  assert denied,'Removed guest retained access';
  execute 'set local role authenticated';
  assert (select count(*) from public.room_events)=0,'Removed guest could read realtime events';
  denied:=false;begin execute 'select * from saantayo_private.rooms';exception when insufficient_privilege then denied:=true;end;
  assert denied,'Direct private table read allowed';
  denied:=false;begin execute 'update public.room_events set revision=99';exception when insufficient_privilege then denied:=true;end;
  assert denied,'Direct event update allowed';
  perform set_config('request.jwt.claim.sub','11111111-1111-1111-1111-111111111111',true);
  assert (select count(*) from public.room_events)=1,'Host cannot read realtime events';
  r:=public.saantayo_room('read',jsonb_build_object('id',id));
  assert r->>'status'='waiting','Authenticated RPC denied';
  execute 'reset role';
end;
$$;
rollback;
